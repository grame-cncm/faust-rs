//! What `faustprobe` prints, recorded: every mode, every format, every entry
//! of every refusal table, the failure paths, `--help`, and the impulse-test
//! corpus through `--protocol impulse-test`.
//!
//! The other test files assert on fragments, which is right for a test and
//! not enough for a refactoring: a line that moved or a note that disappeared
//! passes them. This one runs some four hundred commands and compares what
//! each printed (exit status, stdout, stderr, the files of `--out`) with a
//! recording in `tests/output/expected/`, byte for byte. Of the corpus a run
//! takes one program in [`CORPUS_STRIDE`]; `FAUSTPROBE_CORPUS=all` takes them
//! all, which a bless of the corpus recordings needs. The numbers of
//! `--time` are masked, and nothing else. A stream over [`TEXT_LIMIT`] is
//! recorded as a fingerprint (bytes, lines, FNV-1a 64), which says that it
//! changed, not how: the `$ faustprobe` line of the recording is the command
//! to run by hand.
//!
//! **A change of output is a decision.** When it is the one intended, record
//! it and review the diff of the recordings before committing:
//!
//! ```text
//! FAUSTPROBE_BLESS=1 FAUSTPROBE_CORPUS=all cargo test -p cranelift-ffi --test output_snapshots
//! git diff --stat crates/cranelift-ffi/tests/output/expected
//! ```
//!
//! Paths are relative to the crate (`cargo test` runs there), and what a
//! stream says of the machine (the crate's directory, which a compile error
//! cites in full, the target triple of a diagnostics report, the temporary
//! directory) is masked. Not on Windows: two cases carry the system's
//! wording of a missing file.
//!
//! The comparison is byte for byte on the platform the recordings were made
//! on (`tests/output/expected/PLATFORM`, written by a bless). On another
//! the last digit of a sine or a tangent is the math library's: the text
//! must be the same and the numbers within [`RELATIVE_TOLERANCE`], and a
//! stream recorded as a fingerprint is not compared. So a refactoring is
//! held to the bit where the recordings were made, and to the digits it
//! prints everywhere else.
//!
//! This is the committed form of the harness that gated the restructuring of
//! 2026-09-18 (`porting/faustprobe-restructuring-plan-2026-09-18-en.md`).

#![cfg(not(windows))]

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Where the recordings live, relative to the crate.
const EXPECTED_DIR: &str = "tests/output/expected";
/// The impulse-test corpus, relative to the crate.
const CORPUS_DIR: &str = "../../tests/impulse-tests/dsp";
/// A stream longer than this is recorded as a fingerprint.
const TEXT_LIMIT: usize = 32 * 1024;
/// One corpus program in this many runs by default: the corpus is two thirds
/// of the time, most of it the compiler's, and the protocol path is one.
const CORPUS_STRIDE: usize = 6;
/// Stands for the temporary directory the files of `--out` are written to.
const TMP: &str = "<TMP>";
/// Stands for the crate's directory: a compile error cites the file's
/// absolute path.
const CRATE: &str = "<CRATE>";
/// Stands for the target triple a diagnostics report carries.
const TARGET: &str = "<TARGET>";
/// The file naming the platform the recordings were made on. There the
/// comparison is byte for byte; elsewhere the text must be the same and the
/// numbers within [`RELATIVE_TOLERANCE`], since the last digit of a sine or
/// a tangent is the math library's, and a fingerprint is not compared.
const PLATFORM_FILE: &str = "tests/output/expected/PLATFORM";
/// What another platform's numbers may differ by, relative to the larger.
const RELATIVE_TOLERANCE: f64 = 1e-9;

struct Case {
    name: String,
    args: Vec<String>,
}

fn case(name: &str, args: &[&str]) -> Case {
    Case {
        name: name.to_owned(),
        args: args.iter().map(|a| (*a).to_owned()).collect(),
    }
}

/// The hand-written cases, then the corpus: every program of it when
/// `FAUSTPROBE_CORPUS=all`, one in [`CORPUS_STRIDE`] otherwise. The
/// recordings of all of them are kept, so that a full run finds its own.
fn cases() -> Vec<Case> {
    let full = std::env::var_os("FAUSTPROBE_CORPUS").is_some_and(|v| v == "all");
    let mut cases = hand_written();
    for (index, path) in corpus().into_iter().enumerate() {
        if full || index % CORPUS_STRIDE == 0 {
            cases.push(corpus_case(&path));
        }
    }
    cases
}

/// The corpus programs, sorted by name.
fn corpus() -> Vec<PathBuf> {
    let mut corpus: Vec<PathBuf> = fs::read_dir(CORPUS_DIR)
        .expect("the impulse-test corpus")
        .map(|entry| entry.expect("a corpus entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "dsp"))
        .collect();
    corpus.sort();
    corpus
}

fn corpus_name(path: &Path) -> String {
    format!("corpus_{}", path.file_stem().unwrap().to_string_lossy())
}

fn corpus_case(path: &Path) -> Case {
    case(
        &corpus_name(path),
        &[
            "--protocol",
            "impulse-test",
            "-I",
            CORPUS_DIR,
            &path.to_string_lossy(),
        ],
    )
}

