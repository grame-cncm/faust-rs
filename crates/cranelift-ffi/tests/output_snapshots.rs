fn fnv1a64(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0xcbf2_9ce4_8422_2325_u64, |hash, byte| {
        (hash ^ u64::from(*byte)).wrapping_mul(0x0000_0001_0000_01b3)
    })
}

fn fingerprint(bytes: &[u8]) -> String {
    format!(
        "bytes={} lines={} fnv1a64={:016x}",
        bytes.len(),
        bytes.iter().filter(|b| **b == b'\n').count(),
        fnv1a64(bytes)
    )
}

/// Under `--time`, the lines that carry a duration lose their numbers and
/// the units that follow them (a duration near a millisecond reads `985 us`
/// on one run and `1.02 ms` on the next): the `# time:` lines, and every line
/// of a JSON `"timing"` object.
fn mask_time(text: &str) -> String {
    let numbers = |line: &str| -> String {
        let mut out = String::new();
        let mut in_number = false;
        for ch in line.chars() {
            let numeric = ch.is_ascii_digit()
                || (in_number && matches!(ch, '.' | 'e' | 'E' | '-' | '+'))
                || (ch == '-' && !in_number);
            if numeric {
                if !in_number {
                    out.push('N');
                }
                in_number = true;
            } else {
                in_number = false;
                out.push(ch);
            }
        }
        // `N ms` -> `N T`, the punctuation after the unit kept
        let mut words: Vec<String> = out.split(' ').map(str::to_owned).collect();
        for i in 1..words.len() {
            let unit_end = words[i]
                .find(|c: char| !c.is_ascii_alphabetic())
                .unwrap_or(words[i].len());
            let (unit, rest) = words[i].split_at(unit_end);
            if matches!(unit, "s" | "ms" | "us" | "ns") && words[i - 1].ends_with('N') {
                words[i] = format!("T{rest}");
            }
        }
        words.join(" ")
    };
    let mut out = Vec::new();
    let mut depth = 0usize;
    for line in text.split('\n') {
        let opens = line.matches('{').count();
        let closes = line.matches('}').count();
        if depth == 0 && line.contains("\"timing\"") && opens > closes {
            depth = opens - closes;
            out.push(numbers(line));
        } else if depth > 0 {
            depth = (depth + opens).saturating_sub(closes);
            out.push(numbers(line));
        } else if line.starts_with("# time:") {
            out.push(numbers(line));
        } else {
            out.push(line.to_owned());
        }
    }
    out.join("\n")
}

/// What a stream says of the machine it ran on, replaced by a name: the
/// temporary directory, the crate's directory, the target triple.
fn mask_machine(text: &str, tmp: &str) -> String {
    let crate_dir = Path::new(env!("CARGO_MANIFEST_DIR"))
        .canonicalize()
        .map_or_else(
            |_| env!("CARGO_MANIFEST_DIR").to_owned(),
            |p| p.to_string_lossy().into_owned(),
        );
    let masked = text
        .replace(tmp, TMP)
        .replace(&crate_dir, CRATE)
        .replace(env!("CARGO_MANIFEST_DIR"), CRATE);
    // `"target": "aarch64-macos",` in a diagnostics report
    let mut out = String::with_capacity(masked.len());
    let mut rest = masked.as_str();
    while let Some(at) = rest.find("\"target\": \"") {
        let value_at = at + "\"target\": \"".len();
        let value_len = rest[value_at..].find('"').unwrap_or(rest.len() - value_at);
        out.push_str(&rest[..value_at]);
        out.push_str(TARGET);
        rest = &rest[value_at + value_len..];
    }
    out.push_str(rest);
    out
}

/// One stream of the recording: its text, or its fingerprint when long.
fn stream(label: &str, bytes: &[u8], timed: bool, tmp: &str) -> String {
    if bytes.len() > TEXT_LIMIT {
        return format!("--- {label} (fingerprint)\n{}\n", fingerprint(bytes));
    }
    let text = mask_machine(&String::from_utf8_lossy(bytes), tmp);
    let text = if timed { mask_time(&text) } else { text };
    format!("--- {label}\n{text}\n")
}

/// This platform, as the recordings name theirs.
fn platform() -> String {
    format!("{}-{}", std::env::consts::OS, std::env::consts::ARCH)
}

/// A recording without its fingerprints, which another platform's numbers
/// do not reproduce: the streams recorded as fingerprints and the `--out`
/// files.
fn without_fingerprints(recording: &str) -> String {
    let mut out = Vec::new();
    let mut skipping = false;
    for line in recording.lines() {
        if line.starts_with("--- ") {
            skipping = line.ends_with("(fingerprint)") || line.starts_with("--- file ");
        }
        if !skipping {
            out.push(line);
        }
    }
    out.join("\n")
}

/// The number that starts at `text[at..]`, if one does, as its length: an
/// optional sign, digits, an optional fraction, an optional exponent.
fn number_len(text: &str, at: usize) -> usize {
    let bytes = text.as_bytes();
    let mut i = at;
    if bytes.get(i) == Some(&b'-') {
        i += 1;
    }
    let digits_from = i;
    while bytes.get(i).is_some_and(u8::is_ascii_digit) {
        i += 1;
    }
    if i == digits_from {
        return 0;
    }
    if bytes.get(i) == Some(&b'.') && bytes.get(i + 1).is_some_and(u8::is_ascii_digit) {
        i += 1;
        while bytes.get(i).is_some_and(u8::is_ascii_digit) {
            i += 1;
        }
    }
    if matches!(bytes.get(i), Some(b'e' | b'E')) {
        let mut j = i + 1;
        if matches!(bytes.get(j), Some(b'-' | b'+')) {
            j += 1;
        }
        if bytes.get(j).is_some_and(u8::is_ascii_digit) {
            while bytes.get(j).is_some_and(u8::is_ascii_digit) {
                j += 1;
            }
            i = j;
        }
    }
    i - at
}

/// Cuts a recording into text and numbers, a number being one that a word
/// character does not precede (`out0`, `fnv1a64=` are text).
fn tokens(text: &str) -> Vec<(bool, &str)> {
    let bytes = text.as_bytes();
    let mut out = Vec::new();
    let mut start = 0;
    let mut i = 0;
    while i < text.len() {
        let after_word = i > 0 && (bytes[i - 1].is_ascii_alphanumeric() || bytes[i - 1] == b'_');
        let len = if after_word { 0 } else { number_len(text, i) };
        if len > 0 {
            if start < i {
                out.push((false, &text[start..i]));
            }
            out.push((true, &text[i..i + len]));
            i += len;
            start = i;
        } else {
            i += 1;
        }
    }
    if start < text.len() {
        out.push((false, &text[start..]));
    }
    out
}

/// Whether two recordings say the same on another platform: the same text,
/// and numbers within [`RELATIVE_TOLERANCE`]. The first difference otherwise.
fn same_but_for_the_last_digits(expected: &str, actual: &str) -> Result<(), String> {
    let (expected, actual) = (without_fingerprints(expected), without_fingerprints(actual));
    let (want, got) = (tokens(&expected), tokens(&actual));
    for (k, (a, b)) in want.iter().zip(&got).enumerate() {
        if a == b {
            continue;
        }
        let close = a.0
            && b.0
            && match (a.1.parse::<f64>(), b.1.parse::<f64>()) {
                (Ok(x), Ok(y)) => (x - y).abs() <= RELATIVE_TOLERANCE * x.abs().max(y.abs()),
                _ => false,
            };
        if !close {
            let context: String = want[..k].iter().map(|t| t.1).collect::<String>();
            return Err(format!(
                "`{}` where `{}` was recorded, after line {}",
                b.1,
                a.1,
                context.matches('\n').count() + 1
            ));
        }
    }
    if want.len() != got.len() {
        return Err("one recording is longer than the other".to_owned());
    }
    Ok(())
}

/// Runs one case and returns its recording.
fn record(case: &Case, tmp: &Path) -> String {
    let tmp_text = tmp.to_string_lossy().into_owned();
    let args: Vec<String> = case
        .args
        .iter()
        .map(|a| a.replace(TMP, &tmp_text))
        .collect();
    let out = Command::new(env!("CARGO_BIN_EXE_faustprobe"))
        .args(&args)
        .output()
        .expect("run faustprobe");
    let timed = case.args.iter().any(|a| a == "--time");
    let mut text = format!(
        "$ faustprobe {}\nexit={}\n",
        case.args.join(" "),
        out.status
            .code()
            .map_or("signal".to_owned(), |c| c.to_string())
    );
    text.push_str(&stream("stdout", &out.stdout, timed, &tmp_text));
    text.push_str(&stream("stderr", &out.stderr, timed, &tmp_text));
    // the files of `--out`, by their fingerprint
    for (arg, given) in args.iter().zip(&case.args) {
        if given.starts_with(TMP)
            && let Ok(bytes) = fs::read(arg)
        {
            text.push_str(&format!("--- file {given}\n{}\n", fingerprint(&bytes)));
            let _ = fs::remove_file(arg);
        }
    }
    text
}

#[test]
fn every_case_prints_what_it_printed() {
    let bless = std::env::var_os("FAUSTPROBE_BLESS").is_some();
    let tmp = Path::new(env!("CARGO_TARGET_TMPDIR")).join("faustprobe_output");
    fs::create_dir_all(&tmp).expect("a temporary directory");
    let expected_dir = Path::new(EXPECTED_DIR);
    fs::create_dir_all(expected_dir).expect("the expected directory");

    let recorded_on = fs::read_to_string(PLATFORM_FILE)
        .map(|s| s.trim().to_owned())
        .unwrap_or_default();
    let exact = bless || recorded_on == platform();
    if bless {
        fs::write(PLATFORM_FILE, format!("{}\n", platform())).expect("write the platform");
    }

    let cases = cases();
    let mut names: Vec<String> = cases.iter().map(|c| c.name.clone()).collect();
    names.sort_unstable();
    names.dedup();
    assert_eq!(names.len(), cases.len(), "a case name is used twice");
    // the recordings of the corpus programs a default run skips are not stale
    let mut known: Vec<String> = corpus().iter().map(|p| corpus_name(p)).collect();
    known.extend(names.iter().cloned());

    // the cases are independent, and most of their time is the compiler's:
    // run them on every core, each in a temporary directory of its own
    let workers = std::thread::available_parallelism().map_or(4, usize::from);
    let next = std::sync::atomic::AtomicUsize::new(0);
    let mut recordings: Vec<Option<String>> = (0..cases.len()).map(|_| None).collect();
    let slots = std::sync::Mutex::new(&mut recordings);
    std::thread::scope(|scope| {
        for _ in 0..workers {
            scope.spawn(|| {
                loop {
                    let index = next.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                    let Some(case) = cases.get(index) else { break };
                    let own = tmp.join(&case.name);
                    fs::create_dir_all(&own).expect("a temporary directory");
                    let recording = record(case, &own);
                    slots.lock().expect("recordings")[index] = Some(recording);
                }
            });
        }
    });

    let mut findings: Vec<String> = Vec::new();
    for (case, actual) in cases.iter().zip(recordings) {
        let actual = actual.expect("every case was recorded");
        let path = expected_dir.join(format!("{}.txt", case.name));
        if bless {
            fs::write(&path, &actual).expect("write the recording");
            continue;
        }
        match fs::read_to_string(&path) {
            Ok(expected) if expected == actual => {}
            Ok(expected) if !exact => {
                if let Err(why) = same_but_for_the_last_digits(&expected, &actual) {
                    findings.push(format!(
                        "{}: differs from {} (recorded on {recorded_on}, this is {}): {why}\n    command:  {}",
                        case.name,
                        path.display(),
                        platform(),
                        actual.lines().next().unwrap_or_default()
                    ));
                }
            }
            Ok(expected) => {
                let (line, want, got) = expected
                    .lines()
                    .zip(actual.lines())
                    .enumerate()
                    .find(|(_, (a, b))| a != b)
                    .map_or_else(
                        || {
                            (
                                expected.lines().count().min(actual.lines().count()) + 1,
                                "<end>".to_owned(),
                                "<end>".to_owned(),
                            )
                        },
                        |(i, (a, b))| (i + 1, a.to_owned(), b.to_owned()),
                    );
                findings.push(format!(
                    "{}: differs from {} at line {line}\n    expected: {want}\n    actual:   {got}\n    command:  {}",
                    case.name,
                    path.display(),
                    actual.lines().next().unwrap_or_default()
                ));
            }
            Err(_) => findings.push(format!(
                "{}: no recording at {} (FAUSTPROBE_BLESS=1 records it)",
                case.name,
                path.display()
            )),
        }
    }
    // a recording with no case is stale: a renamed case leaves one behind
    let mut stale: Vec<String> = fs::read_dir(expected_dir)
        .expect("the expected directory")
        .filter_map(|entry| {
            let path = entry.ok()?.path();
            let stem = path.file_stem()?.to_string_lossy().into_owned();
            (path.extension().is_some_and(|e| e == "txt") && !known.contains(&stem)).then_some(path)
        })
        .map(|path| {
            if bless {
                let _ = fs::remove_file(&path);
            }
            format!("{}: recording without a case", path.display())
        })
        .collect();
    if !bless {
        findings.append(&mut stale);
    }
    assert!(
        findings.is_empty(),
        "{} finding(s):\n{}\n\nFAUSTPROBE_BLESS=1 cargo test -p cranelift-ffi --test output_snapshots records what is printed now; review the diff before committing it.",
        findings.len(),
        findings.join("\n")
    );
}
