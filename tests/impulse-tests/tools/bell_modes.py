#!/usr/bin/env python3
"""Writes the modal data of a physmodels.lib bell as a Mojo source file.

The carillon lane (`make mojo-gpu-bells`) runs every mode of every bell as
its own GPU instance, so the host needs each mode's frequency, gain and T60.
They are read here, at build time, from the installed `physmodels.lib`
(`pm.standardBellModel` by default), so that the repository holds no copy of
the library's tables.

    bell_modes.py <physmodels.lib> <out.mojo> [<model> [<t60> <ratio> <slope>]]

The defaults are those `pm.standardBell` passes to its model: T60 30 s,
decay ratio 1, decay slope 2.5.
"""

import re
import sys


def numbers(text):
    return [float(x) for x in re.findall(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", text)]


def main():
    lib, out = sys.argv[1], sys.argv[2]
    model = sys.argv[3] if len(sys.argv) > 3 else "standardBellModel"
    t60, ratio, slope = (
        (float(sys.argv[4]), float(sys.argv[5]), float(sys.argv[6]))
        if len(sys.argv) > 6
        else (30.0, 1.0, 2.5)
    )
    text = open(lib, encoding="utf-8").read()
    start = text.index(f"\n{model}(")
    body = text[start : text.index("\n};", start)]
    n_pos = int(re.search(r"nExPos\s*=\s*(\d+)", body).group(1))
    freqs = numbers(re.search(r"modesFreqs\(n\)\s*=\s*ba\.take\(n\+1,\((.*?)\)\);", body).group(1))
    gains = numbers(re.search(r"waveform\{(.*?)\}", body).group(1))
    fmax = float(re.search(r"modesFreqs\(i\)/([\d.]+)", body).group(1))
    if len(gains) != n_pos * len(freqs):
        sys.exit(f"bell_modes.py: {len(gains)} gains for {n_pos} positions x {len(freqs)} modes")

    def mojo_list(values):
        return ", ".join(repr(v) for v in values)

    with open(out, "w", encoding="utf-8") as f:
        f.write(
            f"""
# Generated by tests/impulse-tests/tools/bell_modes.py from
# {lib}, `pm.{model}`; do not edit.

comptime BELL_MODES = {len(freqs)}
comptime BELL_POSITIONS = {n_pos}
comptime BELL_T60 = {t60}
comptime BELL_T60_RATIO = {ratio}
comptime BELL_T60_SLOPE = {slope}
comptime BELL_T60_FMAX = {fmax}


def bell_freqs() -> List[F64]:
    return [{mojo_list(freqs)}]


# Row p (strike position) holds the gains of the modes struck there.
def bell_gains() -> List[F64]:
    return [{mojo_list(gains)}]
"""
        )


if __name__ == "__main__":
    main()
